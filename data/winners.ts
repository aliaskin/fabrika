function parseTsv(tsv: string, category: WinnerCategory): StaticWinner[] {
  return tsv
    .trim()
    .split('\n')
    .slice(1)
    .map((row, index) => {
      const [fullName, institution, department] = row.split('\t');
      const isHighSchool = category === 'highSchool';

      return {
        id: `${category}-${index}`,
        fullName: fullName.trim(),
        institution: institution.trim(),
        department: isHighSchool ? 'LGS Yerleşimi' : department.trim(),
        category
      };
    });
}

